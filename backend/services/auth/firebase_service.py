# backend/services/auth/firebase_service.py
"""
LEXIS — Firebase Admin Service
-------------------------------
Initializes Firebase Admin SDK and provides utility functions for token verification.
"""

import logging
import os
from typing import Dict, Any, Optional

import firebase_admin
from firebase_admin import credentials, auth as firebase_auth
from core.config import get_settings

logger = logging.getLogger(__name__)
settings = get_settings()

_firebase_app = None


def init_firebase_admin() -> Optional[firebase_admin.App]:
    """
    Initializes the Firebase Admin SDK singleton.
    Uses service_account.json path or environment settings.
    """
    global _firebase_app
    if _firebase_app is not None:
        return _firebase_app

    if firebase_admin._apps:
        _firebase_app = firebase_admin.get_app()
        return _firebase_app

    service_account_path = getattr(settings, "FIREBASE_SERVICE_ACCOUNT_PATH", "firebase/service_account.json")
    
    # Try resolving relative path against backend root if needed
    if not os.path.isabs(service_account_path):
        base_dir = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        service_account_path = os.path.join(base_dir, service_account_path)

    if os.path.exists(service_account_path):
        try:
            cred = credentials.Certificate(service_account_path)
            _firebase_app = firebase_admin.initialize_app(cred)
            logger.info("Firebase Admin SDK initialized successfully with service account file: %s", service_account_path)
            return _firebase_app
        except Exception as e:
            logger.error("Failed to initialize Firebase Admin SDK from certificate: %s", str(e))

    # Fallback to default application credentials or project ID if specified
    try:
        options = {}
        if getattr(settings, "FIREBASE_PROJECT_ID", None):
            options["projectId"] = settings.FIREBASE_PROJECT_ID
        _firebase_app = firebase_admin.initialize_app(options=options if options else None)
        logger.info("Firebase Admin SDK initialized with default options: %s", options)
        return _firebase_app
    except Exception as e:
        logger.error("Failed to initialize Firebase Admin SDK fallback: %s", str(e))
        return None


def verify_firebase_id_token(id_token: str) -> Dict[str, Any]:
    """
    Verifies a Firebase ID token sent from the client SDK.

    Args:
        id_token: JWT string generated by client `user.getIdToken()`.

    Returns:
        Decoded token claims dictionary containing `uid`, `phone_number`, `email`, etc.

    Raises:
        ValueError: If token is invalid or Firebase Admin SDK failed to initialize.
    """
    init_firebase_admin()
    try:
        decoded_token = firebase_auth.verify_id_token(id_token)
        return decoded_token
    except Exception as exc:
        logger.warning("Firebase ID token verification failed: %s", str(exc))
        raise ValueError(f"Invalid Firebase token: {str(exc)}") from exc
